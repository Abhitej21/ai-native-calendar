import { format, isSameDay, parseISO } from 'date-fns';
import { computeDayHealth } from './dayHealth';
import type { CalendarEvent } from '../types';

export function buildDayAgenda(
  events: CalendarEvent[],
  day = new Date(),
): string {
  const dayEvents = events
    .filter((e) => isSameDay(parseISO(e.start), day))
    .sort(
      (a, b) => new Date(a.start).getTime() - new Date(b.start).getTime(),
    );
  const health = computeDayHealth(events, day);
  const title = format(day, 'EEEE, MMM d yyyy');

  const lines = [
    `Pulse agenda — ${title}`,
    `Day health: ${health.score} (${health.label})`,
    `Meetings: ${health.meetingHours}h · Focus: ${health.focusHours}h · Conflicts: ${health.conflicts}`,
    '',
  ];

  if (!dayEvents.length) {
    lines.push('No events scheduled.');
  } else {
    for (const e of dayEvents) {
      const time = `${format(parseISO(e.start), 'h:mm a')} – ${format(parseISO(e.end), 'h:mm a')}`;
      const meta = [
        e.kind,
        e.priority === 'soft' ? 'soft' : null,
        e.attendees?.length ? `with ${e.attendees.join(', ')}` : null,
        e.location || null,
      ]
        .filter(Boolean)
        .join(' · ');
      lines.push(`${time}  ${e.title}`);
      if (meta) lines.push(`           ${meta}`);
      if (e.description) lines.push(`           ${e.description}`);
      lines.push('');
    }
  }

  lines.push('— Generated by Pulse');
  return lines.join('\n');
}

export async function exportDayAgenda(
  events: CalendarEvent[],
  day = new Date(),
): Promise<'copied-and-downloaded' | 'downloaded'> {
  const text = buildDayAgenda(events, day);
  const filename = `pulse-agenda-${format(day, 'yyyy-MM-dd')}.txt`;

  const blob = new Blob([text], { type: 'text/plain;charset=utf-8' });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  a.click();
  URL.revokeObjectURL(url);

  try {
    await navigator.clipboard.writeText(text);
    return 'copied-and-downloaded';
  } catch {
    return 'downloaded';
  }
}
